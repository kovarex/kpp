#include "tests.hpp"

// The runner, in kpp. What the compiler generates calls into it:
// - `int __kpp_test_registered_N = __kppRegisterTest(&__kpp_test_N, "name");` per test (the call's
//   caller location is the test's);
// - `check(a OP b)` evaluates `__kppEqual(a, b)` (or NotEqual, Less...), which notes the operands'
//   text when the comparison fails, and on failure calls `kpp_check_failed(file, line, column, text, kind)` (kind 1
//   check, 2 require: a require throws to end the test);
// - a failing assert calls `kpp_assert_failed`, defined here: inside a test it fails the test.
// Command line: --filter TEXT (repeatable, `*` matches anything), --list, --report FILE (- for
// stdout). Exit code 0 when every test run passed, 1 otherwise, 2 for a bad argument.
std::string testRunnerSource()
{
  return R"kpp(// The test runner, generated by kppc for a --tests build (compiler/src/tests.cpp). The C
// functions it calls (fopen, fputs, fclose, strcmp, abort) are the library's: a declaration of its
// own with other types would be an error (a C function is one function).

struct __KppTestFailure
{
  String file;
  int line = 0;
  int column = 0;
  const char* kind = "check";
  String expression;
  bool hasValues = false;
  String left;
  String right;
};

struct __KppTest
{
  void (*run)();
  const char* name;
  CallerLocation where;
  String fullName;
};

struct __KppTestState
{
  Vector<__KppTest> tests;
  Vector<__KppTestFailure> failures; // the running test's
  bool running = false;
  bool hasValues = false;
  String left;
  String right;
  const char* op = "";
};

__KppTestState& __kppTestState()
{
  static __KppTestState state;
  return state;
}

struct __KppTestEnded {};

int __kppRegisterTest(void (*run)(), const char* name, CallerLocation here = caller)
{
  __KppTest test;
  test.run = run;
  test.name = name;
  test.where = here;
  test.fullName = String(here.file_name());
  test.fullName.append(" > ");
  test.fullName.append(name);
  __kppTestState().tests.push_back(test);
  return 0;
}

// The value as text, when its appendTo or a str() method can say it.
template<typename T> bool __kppShow(const T& value, String& text)
{
  if constexpr (requires { value.appendTo(text); })
  {
    text = String();
    value.appendTo(text);
    return true;
  }
  else if constexpr (isConvertible<const T&, const char*>)
  {
    // C text (`s == "abd"`'s literal), which is no piece of a Text (design.md 14)
    text = String(StringView((const char*)value));
    return true;
  }
  else if constexpr (requires { value.str(); })
  {
    text = String(value.str());
    return true;
  }
  else
    return false;
}

// A failed comparison's operands, for the check's message; false.
template<typename L, typename R> bool __kppNote(const L& l, const R& r, const char* op)
{
  __KppTestState& state = __kppTestState();
  state.hasValues = __kppShow(l, state.left) && __kppShow(r, state.right);
  state.op = op;
  return false;
}
template<typename L, typename R> bool __kppEqual(const L& l, const R& r) { return l == r || __kppNote(l, r, "=="); }
template<typename L, typename R> bool __kppNotEqual(const L& l, const R& r) { return l != r || __kppNote(l, r, "!="); }
template<typename L, typename R> bool __kppLess(const L& l, const R& r) { return l < r || __kppNote(l, r, "<"); }
template<typename L, typename R> bool __kppLessEqual(const L& l, const R& r) { return l <= r || __kppNote(l, r, "<="); }
template<typename L, typename R> bool __kppGreater(const L& l, const R& r) { return l > r || __kppNote(l, r, ">"); }
template<typename L, typename R> bool __kppGreaterEqual(const L& l, const R& r) { return l >= r || __kppNote(l, r, ">="); }

void __kppFail(const char* file, int line, int column, const char* kind, const char* text, const char* message)
{
  __KppTestState& state = __kppTestState();
  __KppTestFailure failure;
  failure.file = String(file);
  failure.line = line;
  failure.column = column;
  failure.kind = kind;
  failure.expression = String(text);
  failure.hasValues = state.hasValues;
  if (state.hasValues)
  {
    failure.left = state.left;
    failure.right = state.right;
    println(StringView(file), ":", line, ":", column, ": ", StringView(message), ": ", StringView(text), " (", state.left, " ",
            StringView(state.op), " ", state.right, ")");
  }
  else
    println(StringView(file), ":", line, ":", column, ": ", StringView(message), ": ", StringView(text));
  state.hasValues = false;
  state.failures.push_back(failure);
}

extern "C" void kpp_check_failed(const char* file, int line, int column, const char* text, int kind)
{
  __kppFail(file, line, column, kind == 2 ? "require" : "check", text, "check failed");
  if (kind == 2)
    throw __KppTestEnded();
}

extern "C" void kpp_assert_failed(const char* file, int line, int column, const char* text)
{
  if (!__kppTestState().running)
  {
    println(StringView(file), ":", line, ":", column, ": assertion failed: ", StringView(text));
    abort();
  }
  __kppFail(file, line, column, "assert", text, "assertion failed");
  throw __KppTestEnded();
}

// Whether text contains the pattern, whose `*` match anything.
bool __kppMatches(const char* text, const char* pattern)
{
  for (int start = 0;; ++start)
  {
    int t = start, p = 0;
    while (true)
    {
      if (pattern[p] == 0)
        return true;
      if (pattern[p] == '*')
        return __kppMatches(text + t, pattern + p + 1);
      if (text[t] == 0 || text[t] != pattern[p])
        break;
      ++t;
      ++p;
    }
    if (text[start] == 0)
      return false;
  }
}

String __kppJson(const String& text)
{
  String result("\"");
  const char* c = text.c_str();
  for (int i = 0; c[i] != 0; ++i)
  {
    if (c[i] == '"' || c[i] == '\\')
    {
      result.append('\\');
      result.append(c[i]);
    }
    else if (c[i] == '\n')
      result.append("\\n");
    else if (c[i] == '\t')
      result.append("\\t");
    else if ((unsigned char)c[i] < 32)
      result.append("?");
    else
      result.append(c[i]);
  }
  result.append('"');
  return result;
}

String __kppJsonTest(const __KppTest& test, bool passed, const Vector<__KppTestFailure>& failures)
{
  String line;
  line << "{\"test\":" << __kppJson(test.fullName) << ",\"file\":" << __kppJson(String(test.where.file_name())) << ",\"line\":"
       << int(test.where.line()) << ",\"status\":\"" << StringView(passed ? "pass" : "fail") << "\",\"failures\":[";
  for (int i = 0; i < int(failures.size()); ++i)
  {
    const __KppTestFailure& f = failures[i];
    if (i > 0)
      line.append(",");
    line << "{\"file\":" << __kppJson(f.file) << ",\"line\":" << f.line << ",\"column\":" << f.column << ",\"kind\":\""
         << StringView(f.kind) << "\",\"expression\":" << __kppJson(f.expression);
    if (f.hasValues)
      line << ",\"values\":[" << __kppJson(f.left) << "," << __kppJson(f.right) << "]";
    line.append("}");
  }
  line.append("]}\n");
  return line;
}

int main(int argc, char** argv)
{
  Vector<const char*> filters;
  bool list = false;
  const char* report = nullptr;
  for (int i = 1; i < argc; ++i)
  {
    if (strcmp(argv[i], "--filter") == 0 && i + 1 < argc)
      filters.push_back(argv[++i]);
    else if (strcmp(argv[i], "--list") == 0)
      list = true;
    else if (strcmp(argv[i], "--report") == 0 && i + 1 < argc)
      report = argv[++i];
    else
    {
      println("unknown test runner argument ", StringView(argv[i]), "; the runner takes --filter TEXT, --list, --report FILE (- for stdout)");
      return 2;
    }
  }
  FILE* reportFile = nullptr;
  bool reportToStdout = report && strcmp(report, "-") == 0;
  if (report && !reportToStdout)
  {
    reportFile = fopen(report, "w");
    if (!reportFile)
    {
      println("cannot write the report ", StringView(report));
      return 2;
    }
  }
  auto writeReport = [&](const String& text)
  {
    if (reportToStdout)
      print(text);
    else if (reportFile)
      fputs(text.c_str(), reportFile);
  };

  __KppTestState& state = __kppTestState();
  // In file and line order, whatever order the registrations ran in.
  Vector<__KppTest>& tests = state.tests;
  for (int i = 1; i < int(tests.size()); ++i)
    for (int j = i; j > 0; --j)
    {
      int byFile = strcmp(tests[j - 1].where.file_name(), tests[j].where.file_name());
      if (byFile < 0 || (byFile == 0 && tests[j - 1].where.line() <= tests[j].where.line()))
        break;
      __KppTest swapped = tests[j - 1];
      tests[j - 1] = tests[j];
      tests[j] = swapped;
    }

  int run = 0, failed = 0;
  for (const __KppTest& test : tests)
  {
    bool selected = filters.empty();
    for (const char* filter : filters)
      selected = selected || __kppMatches(test.fullName.c_str(), filter);
    if (!selected)
      continue;
    if (list)
    {
      println(test.fullName, " (", StringView(test.where.file_name()), ":", int(test.where.line()), ")");
      if (report)
        writeReport(toString("{\"test\":", __kppJson(test.fullName), ",\"file\":", __kppJson(String(test.where.file_name())), ",\"line\":",
                             int(test.where.line()), "}\n"));
      continue;
    }
    ++run;
    state.failures.clear();
    state.running = true;
    try
    {
      test.run();
    }
    catch (const __KppTestEnded&)
    {
    }
    catch (const Exception& e)
    {
      String text = toString("an exception left the test: ", e.message);
      __kppFail(test.where.file_name(), int(test.where.line()), int(test.where.column()), "exception", text.c_str(), "test failed");
    }
    catch (...)
    {
      __kppFail(test.where.file_name(), int(test.where.line()), int(test.where.column()), "exception", "an exception left the test",
                "test failed");
    }
    state.running = false;
    bool passed = state.failures.empty();
    if (!passed)
    {
      ++failed;
      println("failed: ", test.fullName);
    }
    writeReport(__kppJsonTest(test, passed, state.failures));
  }
  if (list)
  {
    if (reportFile)
      fclose(reportFile);
    return 0;
  }
  writeReport(toString("{\"summary\":{\"tests\":", run, ",\"failed\":", failed, "}}\n"));
  if (reportFile)
    fclose(reportFile);
  println(run, " ", StringView(run == 1 ? "test" : "tests"), ", ", failed, " failed");
  return failed ? 1 : 0;
}
)kpp";
}
