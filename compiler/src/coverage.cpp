// Without the test runner: the program's exit writes it.
extern "C" void kpp_coverage_at_exit()
{
  if (__kppCoverageState().managed)
    return;
  const char* path = std::getenv("KPP_COVERAGE_FILE");
  kpp_coverage_write(path && *path ? path : kpp_coverage_default_path());
}

