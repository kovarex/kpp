# Project files for an IDE (docs/build.md, "Project files for an IDE"): kppc writes a Visual Studio
# solution and .vscode for tests\run\hello.kpp; MSBuild builds the solution in debug and release, and
# each program prints hello.expected; an error reaches MSBuild with the file's absolute path and line,
# so that the Error List opens it; .vscode's files are JSON after their first line. run_tests.cmd runs it.
param([string]$Kppc = "$PSScriptRoot\..\build\kppc.exe")
$ErrorActionPreference = 'Stop'
$work = Join-Path $PSScriptRoot '..\build\tests\generate'
if (Test-Path $work) { Remove-Item -Recurse -Force $work }
New-Item -ItemType Directory -Force $work | Out-Null
Copy-Item "$PSScriptRoot\run\hello.kpp" $work
$Kppc = (Resolve-Path $Kppc).Path
$expected = Get-Content "$PSScriptRoot\run\hello.expected"
$failed = 0
function Fail([string]$what) { Write-Output "FAIL generate: $what"; $script:failed++ }

$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$msbuild = & $vswhere -latest -requires Microsoft.Component.MSBuild -find 'MSBuild\**\Bin\MSBuild.exe' | Select-Object -First 1

Push-Location $work
try
{
  & $Kppc --generate-visual-studio-files --generate-vs-code-files --exe build\hello.exe hello.kpp | Out-Null
  if ($LASTEXITCODE -ne 0) { Fail "kppc exited with $LASTEXITCODE" }
  $filters = Get-Content 'build\visual-studio\hello.vcxproj.filters' -Raw
  if ($filters -notmatch 'Filter Include="Standard Library"') { Fail 'the standard library is not a folder of the project' }
  foreach ($file in 'tasks', 'launch', 'settings')
  {
    $lines = Get-Content ".vscode\$file.json"
    if ($lines[0] -notmatch '^// Generated by kppc') { Fail ".vscode\$file.json has no generated mark" }
    try { ($lines | Select-Object -Skip 1) -join "`n" | ConvertFrom-Json | Out-Null } catch { Fail ".vscode\$file.json is not JSON: $_" }
  }
  foreach ($configuration in 'Debug', 'Release')
  {
    $log = & $msbuild -nologo -v:m "-p:Configuration=$configuration" -p:Platform=x64 'build\visual-studio\hello.sln' 2>&1
    if ($LASTEXITCODE -ne 0) { Fail "MSBuild $configuration`n$($log -join "`n")"; continue }
    $output = & ".\build\$($configuration.ToLower())\hello.exe"
    if (($output -join "`n") -ne ($expected -join "`n")) { Fail "the $configuration program printed $output" }
  }
  # An error: the absolute path and the line, the form MSBuild puts in the Error List.
  Add-Content hello.kpp "`nint broken() { return undefinedThing; }"
  $log = & $msbuild -nologo -v:m -p:Configuration=Debug -p:Platform=x64 'build\visual-studio\hello.sln' 2>&1
  $path = [regex]::Escape((Resolve-Path hello.kpp).Path)
  if ($LASTEXITCODE -eq 0 -or -not ($log -match "^\s*$path\(\d+\): error : ")) { Fail "the error is not in MSBuild's form:`n$($log -join "`n")" }
  # The servers the builds started: each task's command after --server, with --stop-server.
  $tasks = (Get-Content '.vscode\tasks.json' | Select-Object -Skip 1) -join "`n" | ConvertFrom-Json
  foreach ($task in $tasks.tasks)
  {
    $command = $task.args[3]
    $rest = $command.Substring($command.IndexOf('--server ') + 9)
    & cmd /d /c "`"$Kppc`" --stop-server $rest" | Out-Null
  }
}
finally { Pop-Location }
if ($failed -eq 0) { Write-Output 'ok   generate' }
exit $failed
