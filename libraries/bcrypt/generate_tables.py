# Writes src/BlowfishTables.kpp: Blowfish's initial P-array and S-boxes, which are the
# hexadecimal digits of pi's fraction (Schneier 1993), computed here with Machin's formula.
# Usage: python generate_tables.py (from libraries/bcrypt).
import os

WORDS = 18 + 4 * 256
DIGITS = WORDS * 8

def arctan_inverse(x, one):
    # arctan(1/x) * one, by its Taylor series in integers.
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total

guard = 16
one = 16 ** (DIGITS + guard)
pi = 4 * (4 * arctan_inverse(5, one) - arctan_inverse(239, one))
fraction = (pi - 3 * one) >> (4 * guard)
digits = format(fraction, "0%dx" % DIGITS)
words = [int(digits[i * 8:i * 8 + 8], 16) for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B and words[18] == 0xD1310BA6
assert words[-1] == 0x3AC372E6

def table(name, values):
    lines = ["const uint32_t %s[%d] = {" % (name, len(values))]
    for i in range(0, len(values), 6):
        lines.append("  " + ", ".join("0x%08xu" % v for v in values[i:i + 6]) + ",")
    lines.append("};")
    return "\n".join(lines)

out = ["// Generated by generate_tables.py: the hexadecimal digits of pi's fraction, which Blowfish",
       "// starts from. Do not edit.", "",
       table("blowfishInitialP", words[:18]), ""]
for box in range(4):
    out.append(table("blowfishInitialS%d" % box, words[18 + 256 * box:18 + 256 * (box + 1)]))
    out.append("")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "BlowfishTables.kpp")
with open(path, "w", newline="\n") as f:
    f.write("\n".join(out))
