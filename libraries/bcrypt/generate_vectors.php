<?php
// Writes tests/BcryptPhpVectors.kpp: bcrypt hashes from PHP's crypt() (its crypt_blowfish), the
// implementation gorating.com's password_hash() hashes came from.
// Usage: php generate_vectors.php (from libraries/bcrypt; PHP 8).
mt_srand(20261102);
$alphabet = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
$lines = [];
$lengths = [0, 1, 2, 3, 4, 7, 8, 15, 16, 31, 32, 55, 56, 70, 71, 72, 73, 100, 255];
$i = 0;
foreach ($lengths as $length)
  foreach ([false, true] as $highBytes)
  {
    $password = "";
    for ($j = 0; $j < $length; $j++)
      $password .= chr($highBytes ? mt_rand(1, 255) : mt_rand(32, 126));
    $salt = "";
    for ($j = 0; $j < 21; $j++)
      $salt .= $alphabet[mt_rand(0, 63)];
    $salt .= $alphabet[mt_rand(0, 3) * 16];
    $cost = ($i++ % 3 == 0) ? 5 : 4;
    $hash = crypt($password, sprintf('$2y$%02d$', $cost).$salt);
    if (strlen($hash) != 60)
      die("crypt failed\n");
    $lines[] = "  {\"".bin2hex($password)."\", \"".$hash."\"},";
  }
$out = "// Generated by generate_vectors.php from PHP ".PHP_VERSION."'s crypt(). Do not edit.\n".
       "// {password in hex, its $2y$ hash}\n".
       "const char* bcryptPhpVectors[][2] = {\n".implode("\n", $lines)."\n};\n".
       "const int bcryptPhpVectorCount = ".count($lines).";\n";
file_put_contents(__DIR__."/tests/BcryptPhpVectors.kpp", $out);
