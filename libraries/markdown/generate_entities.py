"""Writes src/MarkdownEntities.kpp: the HTML5 named character references that end in ';' (the ones
CommonMark recognizes), from Python's html.entities.html5, which is the WHATWG list.

    python generate_entities.py
"""
import html.entities
import sys
from pathlib import Path


def literal(text: str) -> str:
    out = []
    for b in text.encode("utf-8"):
        c = chr(b)
        if c in '"\\?' or b < 0x20 or b >= 0x7F:
            out.append("\\%03o" % b)
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


names = sorted(name[:-1] for name in html.entities.html5 if name.endswith(";"))
lines = [
    "// Generated by generate_entities.py from Python " + sys.version.split()[0] + "'s html.entities.html5 (the WHATWG list of",
    "// named character references): the " + str(len(names)) + " that end in ';'. Do not edit.",
    "",
    "struct MarkdownEntityName",
    "{",
    "  const char* name;",
    "  const char* value;",
    "};",
    "",
    "const MarkdownEntityName markdownEntityNames[] = {",
]
for name in names:
    lines.append("  {%s, %s}," % (literal(name), literal(html.entities.html5[name + ";"])))
lines += [
    "};",
    "",
    "// The UTF-8 text of a named character reference (without '&' and ';'), or nullptr.",
    "const char* markdownNamedEntity(StringView name)",
    "{",
    "  int low = 0;",
    "  int high = " + str(len(names)) + ";",
    "  while (low < high)",
    "  {",
    "    int middle = (low + high) / 2;",
    "    int compare = strcmp(String(name).c_str(), markdownEntityNames[middle].name);",
    "    if (compare == 0)",
    "      return markdownEntityNames[middle].value;",
    "    if (compare < 0)",
    "      high = middle;",
    "    else",
    "      low = middle + 1;",
    "  }",
    "  return nullptr;",
    "}",
    "",
]
Path(__file__).with_name("src").joinpath("MarkdownEntities.kpp").write_text("\n".join(lines), encoding="utf-8", newline="\n")
