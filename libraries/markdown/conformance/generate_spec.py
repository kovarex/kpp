"""Writes OUT/CommonMarkSpec.kpp: the examples of the CommonMark spec (spec.txt of
https://github.com/commonmark/commonmark-spec) and the table examples of the GFM spec
(test/spec.txt of https://github.com/github/cmark-gfm), both CC-BY-SA 4.0, as kpp data for
CommonMarkTests.kpp.in. The examples are copied unchanged, so the generated file is under the
specs' license, which is why run.cmd writes it outside the repository.

    python generate_spec.py PATH-TO-A-commonmark-spec-CLONE PATH-TO-A-cmark-gfm-CLONE OUT

An example is the text between a line of 32 backticks followed by " example" and the closing line
of 32 backticks: the Markdown, a line with ".", the HTML; "→" stands for a tab.
"""
import re
import subprocess
import sys
from pathlib import Path

FENCE = "`" * 32


def literal(text: str) -> str:
    out = []
    for b in text.encode("utf-8"):
        c = chr(b)
        if c in '"\\?' or b < 0x20 or b >= 0x7F:
            out.append("\\%03o" % b)
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def read(spec: Path, kind: str):
    """The spec's version and its examples whose fence line says kind ("example", "example table")."""
    lines = spec.read_text(encoding="utf-8").split("\n")
    version = next(l for l in lines if l.startswith("version:")).split(" ")[1].strip("'")
    examples = []
    section = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        heading = re.match(r"^#{1,6} (.*)", line)
        if heading:
            section = heading.group(1)
        if line.startswith(FENCE) and line[len(FENCE):].strip().startswith("example"):
            wanted = line[len(FENCE):].strip() == kind
            i += 1
            markdown = []
            while lines[i] != ".":
                markdown.append(lines[i])
                i += 1
            i += 1
            html = []
            while not lines[i].startswith(FENCE):
                html.append(lines[i])
                i += 1
            md = "\n".join(markdown).replace("→", "\t")
            out = "\n".join(html).replace("→", "\t")
            if wanted:
                examples.append((section, md + "\n" if markdown else "", out + "\n" if html else ""))
        i += 1
    return version, examples


def head(clone: Path) -> str:
    return subprocess.run(["git", "-C", str(clone), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()


def main():
    commonmark = Path(sys.argv[1])
    gfm = Path(sys.argv[2])
    version, examples = read(commonmark / "spec.txt", "example")
    gfmVersion, tables = read(gfm / "test" / "spec.txt", "example table")
    out = [
        "// Generated by generate_spec.py: the " + str(len(examples)) + " examples of the CommonMark spec " + version + " (commonmark-spec",
        "// " + head(commonmark) + "), and the " + str(len(tables)) + " table examples of the GFM spec " + gfmVersion + " (cmark-gfm",
        "// " + head(gfm) + "). The specs and so this file: CC-BY-SA 4.0, John MacFarlane and GitHub. Do not edit.",
        "",
        "struct CommonMarkExample",
        "{",
        "  int number;",
        "  const char* section;",
        "  const char* markdown;",
        "  const char* html;",
        "};",
        "",
        "const CommonMarkExample commonMarkExamples[] = {",
    ]
    for n, (section, md, html) in enumerate(examples, 1):
        out.append("  {%d, %s, %s, %s}," % (n, literal(section), literal(md), literal(html)))
    out += ["};", "", "const CommonMarkExample gfmTableExamples[] = {"]
    for n, (section, md, html) in enumerate(tables, 1):
        out.append("  {%d, %s, %s, %s}," % (n, literal(section), literal(md), literal(html)))
    out += ["};", ""]
    Path(sys.argv[3]).joinpath("CommonMarkSpec.kpp").write_text("\n".join(out), encoding="utf-8", newline="\n")


main()
