"""Writes src/MarkdownUnicode.kpp from Python's unicodedata: the code point ranges of Unicode's P
(punctuation) and S (symbol) categories, which CommonMark 0.31 calls Unicode punctuation, and full
case folding (str.casefold), which link labels are compared by.

    python generate_unicode.py
"""
import sys
import unicodedata
from pathlib import Path

ranges = []
for code in range(0x80, 0x110000):
    if unicodedata.category(chr(code))[0] in "PS":
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
lines = [
    "// Generated by generate_unicode.py from Python " + sys.version.split()[0] + "'s unicodedata (Unicode " + unicodedata.unidata_version + "): the",
    "// ranges of the P and S categories above ASCII. Do not edit.",
    "",
    "const int markdownPunctuationRanges[][2] = {",
]
for first, last in ranges:
    lines.append("  {0x%X, 0x%X}," % (first, last))
folds = []
for code in range(0x80, 0x110000):
    c = chr(code)
    if 0xD800 <= code <= 0xDFFF:
        continue
    if c.casefold() != c:
        folds.append((code, c.casefold()))


def literal(text):
    return '"' + "".join("\\%03o" % b for b in text.encode("utf-8")) + '"'


lines += [
    "};",
    "",
    "struct MarkdownCaseFold",
    "{",
    "  int code;",
    "  const char* folded;",
    "};",
    "",
    "// Every code point above ASCII whose case folding differs, with its folding.",
    "const MarkdownCaseFold markdownCaseFolds[] = {",
]
for code, folded in folds:
    lines.append("  {0x%X, %s}," % (code, literal(folded)))
lines += [
    "};",
    "",
    "// Appends the code point case folded (Unicode's full folding: U+1E9E is ss).",
    "void markdownAppendFolded(String& out, int c)",
    "{",
    "  if (c < 0x80)",
    "  {",
    "    out.append(char(c >= 'A' && c <= 'Z' ? c + 32 : c));",
    "    return;",
    "  }",
    "  int low = 0;",
    "  int high = " + str(len(folds)) + ";",
    "  while (low < high)",
    "  {",
    "    int middle = (low + high) / 2;",
    "    if (c < markdownCaseFolds[middle].code)",
    "      high = middle;",
    "    else if (c > markdownCaseFolds[middle].code)",
    "      low = middle + 1;",
    "    else",
    "    {",
    "      out.append(markdownCaseFolds[middle].folded);",
    "      return;",
    "    }",
    "  }",
    "  markdownAppendUtf8(out, c);",
    "}",
    "",
    "bool markdownIsNonAsciiPunctuation(int c)",
    "{",
    "  int low = 0;",
    "  int high = " + str(len(ranges)) + ";",
    "  while (low < high)",
    "  {",
    "    int middle = (low + high) / 2;",
    "    if (c < markdownPunctuationRanges[middle][0])",
    "      high = middle;",
    "    else if (c > markdownPunctuationRanges[middle][1])",
    "      low = middle + 1;",
    "    else",
    "      return true;",
    "  }",
    "  return false;",
    "}",
    "",
]
Path(__file__).with_name("src").joinpath("MarkdownUnicode.kpp").write_text("\n".join(lines), encoding="utf-8", newline="\n")
