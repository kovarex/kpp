"""Writes JsonTestSuite.kpp: the parsing cases of Nicolas Seriot's JSONTestSuite
(https://github.com/nst/JSONTestSuite, MIT license, test_parsing/), as kpp data for
JsonSuiteTests.kpp.

    python generate_suite.py PATH-TO-A-JSONTestSuite-CLONE

The files are read from the clone's HEAD with git (some names cannot be checked out on Windows).
y_ files must parse, n_ files must not; i_ files are the RFC's implementation-defined cases,
whose result is the table below (README.md says why).
"""
import subprocess
import sys
from pathlib import Path

# i_ cases this library accepts; every other i_ case is rejected.
ACCEPTED = {
    # A number whose double is 0 or rounds: parsed to the nearest double.
    "i_number_double_huge_neg_exp.json",
    "i_number_real_underflow.json",
    "i_number_too_big_neg_int.json",
    "i_number_too_big_pos_int.json",
    "i_number_very_big_negative_int.json",
    # Nesting up to 1000 levels.
    "i_structure_500_nested_arrays.json",
}


def literal(data: bytes) -> str:
    out = []
    for b in data:
        c = chr(b)
        if c == '"' or c == '\\':
            out.append('\\' + c)
        elif 0x20 <= b < 0x7F and c != '?':
            out.append(c)
        else:
            out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def main():
    clone = Path(sys.argv[1])
    head = subprocess.run(["git", "-C", str(clone), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    names = subprocess.run(["git", "-C", str(clone), "ls-tree", "--name-only", "HEAD", "test_parsing/"],
                           capture_output=True, text=True, check=True).stdout.split()
    lines = [
        "// Generated by generate_suite.py from JSONTestSuite " + head + " (https://github.com/nst/JSONTestSuite,",
        "// MIT license, Copyright (c) 2016 Nicolas Seriot): its test_parsing/ files. Do not edit.",
        "",
        "struct JsonSuiteCase",
        "{",
        "  const char* name;",
        "  const char* text;",
        "  int length;",
        "  bool accept; // y_ cases, and the i_ cases this library accepts",
        "};",
        "",
        "const JsonSuiteCase jsonSuiteCases[] = {",
    ]
    for path in sorted(names):
        name = path.split("/")[-1]
        if not name.endswith(".json"):
            continue
        data = subprocess.run(["git", "-C", str(clone), "cat-file", "blob", "HEAD:" + path], capture_output=True, check=True).stdout
        accept = name.startswith("y_") or name in ACCEPTED
        lines.append("  {%s, %s, %d, %s}," % (literal(name.encode()), literal(data), len(data), "true" if accept else "false"))
    lines.append("};")
    lines.append("")
    Path(__file__).with_name("JsonTestSuite.kpp").write_text("\n".join(lines), encoding="utf-8", newline="\n")


main()
