# Writes kpp.colors.pkgdef: each of kpp's classifications (Colors.cs) with its default color per Visual Studio
# theme (docs/editors.md, "Colors"). build.cmd runs it, so the table below is what a build ships; the output is
# checked in beside it. Light and the two Blue themes are VS Code's Light Modern, Dark is Dark Modern: the panel
# kovarex picked (2026-11-09). High Contrast keeps the system's text color, as Visual Studio's C++ colors do.
#
# Where they go, as Visual Studio's own packages do it (VCEditorColors.pkgdef, "Cpp Text Editor MEF Items"): a key
# per theme, named for this package alone, whose Data is one category, Text Editor MEF Items, with an entry per
# format definition's [Name]. A classification's color in code is one color for every theme; this is what
# makes it follow the theme, and a user's change in Tools > Options > Fonts and Colors still wins.
$ErrorActionPreference = 'Stop'

# name (Colors.cs), Light Modern, Dark Modern
$colors = @(
  @('kpp local',           '001080', '9CDCFE'),
  @('kpp parameter',       '001080', '9CDCFE'),
  @('kpp member',          '001080', '9CDCFE'),
  @('kpp static member',   '001080', '9CDCFE'),
  @('kpp global',          '001080', '9CDCFE'),
  @('kpp namespace',       '267F99', '4EC9B0'),
  @('kpp type',            '267F99', '4EC9B0'),
  @('kpp function',        '795E26', 'DCDCAA'),
  @('kpp method',          '795E26', 'DCDCAA'),
  @('kpp enumerator',      '0070C1', '4FC1FF'),
  @('kpp control keyword', 'AF00DB', 'C586C0'),
  @('kpp number',          '098658', 'B5CEA8'),
  @('kpp number type',     '3B3B3B', 'CCCCCC'),
  @('kpp string',          'A31515', 'CE9178'),
  @('kpp string escape',   'EE0000', 'D7BA7D'),
  @('kpp comment',         '008000', '6A9955'),
  @('kpp operator',        '000000', 'D4D4D4')
)

# theme, its GUID, the column of $colors (0: the system's text color)
$themes = @(
  @('Light',                 'de3dbbcd-f642-433c-8353-8f1df4370aba', 1),
  @('Blue',                  'a4d6a176-b948-4b29-8c66-53c97a1ed7d0', 1),
  @('Blue (Extra Contrast)', 'ce94d289-8481-498b-8ca9-9b6191a315b9', 1),
  @('Dark',                  '1ded0138-47ce-435e-84ef-9ec1f439b749', 2),
  @('High Contrast',         'a5c004b4-2d4b-494e-bf01-45fc492522c7', 0)
)

# Text Editor MEF Items, the category of a classification's colors.
$category = [Guid]'75A05685-00A8-4DED-BAE5-E7A50BFA929A'

function Blob($column)
{
  $body = New-Object IO.MemoryStream
  $w = New-Object IO.BinaryWriter $body
  $w.Write([int]11)    # the format's version
  $w.Write([int]1)     # one category
  $w.Write($category.ToByteArray())
  $w.Write([int]$colors.Count)
  foreach ($c in $colors)
  {
    $name = [Text.Encoding]::ASCII.GetBytes($c[0])
    $w.Write([int]$name.Length)
    $w.Write($name)
    $w.Write([byte]0)  # no background
    if ($column -eq 0)
    {
      # CT_SYSCOLOR, COLOR_WINDOWTEXT.
      $w.Write([byte]3); $w.Write([byte]8); $w.Write([byte]0); $w.Write([byte]0); $w.Write([byte]0)
    }
    else
    {
      # CT_RAW: red, green, blue, alpha.
      $hex = $c[$column]
      $w.Write([byte]1)
      foreach ($at in 0, 2, 4) { $w.Write([Convert]::ToByte($hex.Substring($at, 2), 16)) }
      $w.Write([byte]255)
    }
  }
  $w.Flush()
  $bytes = $body.ToArray()
  # The whole blob's length comes first, itself included.
  [BitConverter]::GetBytes([int]($bytes.Length + 4)) + $bytes
}

$out = New-Object Text.StringBuilder
[void]$out.Append("// Generated by make-colors.ps1, which has the table: kpp's classifications' colors per theme.`r`n")
foreach ($t in $themes)
{
  [void]$out.Append("`r`n// $($t[0])`r`n[`$RootKey`$\Themes\{$($t[1])}\kpp Text Editor MEF Items]`r`n")
  [void]$out.Append('"Data"=hex:' + (((Blob $t[2]) | ForEach-Object { $_.ToString('x2') }) -join ',') + "`r`n")
}
[IO.File]::WriteAllText("$PSScriptRoot\kpp.colors.pkgdef", $out.ToString(), (New-Object Text.UTF8Encoding $false))
